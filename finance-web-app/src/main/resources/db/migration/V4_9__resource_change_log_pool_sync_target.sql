ALTER TABLE `RESOURCE_CHANGE_LOG`
    ADD COLUMN `POOL_SYNC_TARGET` VARCHAR(32) NULL COMMENT '资源同步目标类型：CLOUD/INDEPENDENT' AFTER `UPSTREAM_SERVER_ID`;

UPDATE `RESOURCE_CHANGE_LOG`
SET `POOL_SYNC_TARGET` = 'INDEPENDENT'
WHERE `POOL_SYNC_TARGET` IS NULL
  AND (
    `DATA_SNAPSHOT` LIKE '%"poolSyncTarget":"INDEPENDENT"%'
    OR `DATA_SNAPSHOT` LIKE '%"poolSyncTarget":"DEDICATED"%'
    OR (`DATA_SNAPSHOT` LIKE '%"machineId":%' AND `DATA_SNAPSHOT` NOT LIKE '%"hostName":%')
  );

UPDATE `RESOURCE_CHANGE_LOG`
SET `POOL_SYNC_TARGET` = 'CLOUD'
WHERE `POOL_SYNC_TARGET` IS NULL
  AND (
    `DATA_SNAPSHOT` LIKE '%"poolSyncTarget":"CLOUD"%'
    OR `DATA_SNAPSHOT` LIKE '%"poolSyncTarget":"ECS"%'
    OR `DATA_SNAPSHOT` LIKE '%"hostName":%'
  );
