-- 会员备注 + 未写 COLLATE 的表在 MySQL 8 上落成 utf8mb4_0900_ai_ci，与历史表联查会报错。
SET @sql = (
  SELECT IF(
    (SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE()
       AND UPPER(TABLE_NAME) = 'BUSINESS_VHOST'
       AND UPPER(COLUMN_NAME) = 'MEMBER_REMARK') > 0,
    'SELECT 1',
    'ALTER TABLE `BUSINESS_VHOST` ADD COLUMN `MEMBER_REMARK` varchar(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT ''会员备注'' AFTER `REMARK`'
  )
);
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

