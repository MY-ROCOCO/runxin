CREATE TABLE IF NOT EXISTS `MEMBER_CONTACT_PROFILE` (
  `ID` bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  `MEMBER_ID` bigint NOT NULL COMMENT '会员ID',
  `PROVINCE_CODE` varchar(64) DEFAULT NULL COMMENT '省编码',
  `PROVINCE_NAME` varchar(128) DEFAULT NULL COMMENT '省名称',
  `CITY_CODE` varchar(64) DEFAULT NULL COMMENT '市编码',
  `CITY_NAME` varchar(128) DEFAULT NULL COMMENT '市名称',
  `DISTRICT_CODE` varchar(64) DEFAULT NULL COMMENT '区县编码',
  `DISTRICT_NAME` varchar(128) DEFAULT NULL COMMENT '区县名称',
  `DETAIL_ADDRESS` varchar(500) DEFAULT NULL COMMENT '详细地址',
  `POSTAL_CODE` varchar(32) DEFAULT NULL COMMENT '邮政编码',
  `FIXED_PHONE` varchar(64) DEFAULT NULL COMMENT '固定电话',
  `FAX` varchar(64) DEFAULT NULL COMMENT '传真',
  `SORT_CODE` int DEFAULT NULL COMMENT '排序',
  `EXT_JSON` longtext COMMENT '扩展信息',
  `DELETE_FLAG` varchar(255) DEFAULT NULL COMMENT '删除标志',
  `CREATE_TIME` datetime DEFAULT NULL COMMENT '创建时间',
  `CREATE_USER` varchar(20) DEFAULT NULL COMMENT '创建用户',
  `UPDATE_TIME` datetime DEFAULT NULL COMMENT '更新时间',
  `UPDATE_USER` varchar(20) DEFAULT NULL COMMENT '更新用户',
  PRIMARY KEY (`ID`) USING BTREE,
  KEY `IDX_MEMBER_CONTACT_PROFILE_MEMBER_ID` (`MEMBER_ID`) USING BTREE
) ENGINE=InnoDB COMMENT='会员联系地址资料';

