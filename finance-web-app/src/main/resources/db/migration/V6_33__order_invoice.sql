  UNIQUE KEY `UK_ORDER_NO` (`ORDER_NO`) USING BTREE,
  KEY `IDX_INVOICE_ID` (`INVOICE_ID`) USING BTREE,
  KEY `IDX_MEMBER_NO` (`MEMBER_NO`) USING BTREE
