CREATE TABLE IF NOT EXISTS `ORDER_INVOICE` (
  `ID` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '主键ID',
  `INVOICE_NO` varchar(40) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '发票申请号',
  `MEMBER_NO` bigint NOT NULL COMMENT '会员编号',
  `TITLE` varchar(200) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '发票抬头',
  `TAX_NO` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '税号',
  `EMAIL` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '接收邮箱',
  `INVOICE_AMOUNT` decimal(12,2) NOT NULL DEFAULT '0.00' COMMENT '开票金额（所选订单实付合计）',
  `ORDER_COUNT` int NOT NULL DEFAULT 0 COMMENT '明细订单笔数',
  `STATUS` int NOT NULL DEFAULT 0 COMMENT '状态：0待审核 1已开具 -1已拒绝',
  `REJECT_REASON` varchar(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '拒绝原因',
  `APPLY_TIME` datetime DEFAULT NULL COMMENT '申请时间',
  `ISSUE_TIME` datetime DEFAULT NULL COMMENT '开具时间',
  `ISSUE_USER` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '开具管理员ID',
  `DELETE_FLAG` varchar(255) DEFAULT NULL COMMENT '删除标志',
  `CREATE_TIME` datetime DEFAULT NULL COMMENT '创建时间',
  `CREATE_USER` varchar(20) DEFAULT NULL COMMENT '创建用户',
  `UPDATE_TIME` datetime DEFAULT NULL COMMENT '更新时间',
  `UPDATE_USER` varchar(20) DEFAULT NULL COMMENT '更新用户',
  PRIMARY KEY (`ID`) USING BTREE,
  UNIQUE KEY `UK_INVOICE_NO` (`INVOICE_NO`) USING BTREE,
  KEY `IDX_MEMBER_NO_STATUS` (`MEMBER_NO`, `STATUS`) USING BTREE,
  KEY `IDX_STATUS_APPLY_TIME` (`STATUS`, `APPLY_TIME`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='订单发票申请主表';

