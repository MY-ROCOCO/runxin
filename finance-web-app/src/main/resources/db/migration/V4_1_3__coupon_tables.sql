-- =====================================================================
-- 优惠券功能：模板、会员券、订单关联与订单金额扩展字段
-- =====================================================================

CREATE TABLE IF NOT EXISTS `COUPON_TEMPLATE` (
  `ID` varchar(20) NOT NULL COMMENT '主键',
  `COUPON_NAME` varchar(100) NOT NULL COMMENT '优惠券名称',
  `COUPON_DESCRIPTION` varchar(255) DEFAULT NULL COMMENT '优惠券描述',
  `COUPON_TYPE` int NOT NULL COMMENT '优惠券类型：1固定金额 2折扣券 3满减券',
  `THRESHOLD_AMOUNT` decimal(10,2) DEFAULT 0.00 COMMENT '使用门槛金额',
  `REDUCE_AMOUNT` decimal(10,2) DEFAULT 0.00 COMMENT '固定减免金额',
  `DISCOUNT_RATE` decimal(10,4) DEFAULT NULL COMMENT '折扣率，例如 0.9000 表示 9 折',
  `MAX_DISCOUNT_AMOUNT` decimal(10,2) DEFAULT NULL COMMENT '折扣券封顶金额',
  `APPLY_PRODUCT_TYPES` varchar(64) DEFAULT NULL COMMENT '适用产品类型，逗号分隔',
  `STATUS` int NOT NULL DEFAULT 1 COMMENT '状态：0禁用 1启用',
  `ISSUE_TOTAL_COUNT` int NOT NULL DEFAULT 0 COMMENT '计划发放总量，0表示不限制',
  `ISSUED_COUNT` int NOT NULL DEFAULT 0 COMMENT '已发放数量',
  `USE_LIMIT` int NOT NULL DEFAULT 1 COMMENT '单张券可使用次数',
  `START_TIME` datetime DEFAULT NULL COMMENT '生效时间',
  `END_TIME` datetime DEFAULT NULL COMMENT '失效时间',
  `SORT_CODE` int DEFAULT 0 COMMENT '排序码',
  `EXT_JSON` varchar(1000) DEFAULT NULL COMMENT '扩展字段',
  `DELETE_FLAG` varchar(20) NOT NULL DEFAULT 'NOT_DELETE' COMMENT '删除标志',
  `CREATE_TIME` datetime DEFAULT NULL COMMENT '创建时间',
  `CREATE_USER` varchar(20) DEFAULT NULL COMMENT '创建人',
  `UPDATE_TIME` datetime DEFAULT NULL COMMENT '更新时间',
  `UPDATE_USER` varchar(20) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`ID`),
  KEY `IDX_COUPON_TEMPLATE_STATUS` (`STATUS`),
  KEY `IDX_COUPON_TEMPLATE_TIME` (`START_TIME`,`END_TIME`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='优惠券模板表';

CREATE TABLE IF NOT EXISTS `MEMBER_COUPON` (
  `ID` varchar(20) NOT NULL COMMENT '主键',
  `TEMPLATE_ID` varchar(20) NOT NULL COMMENT '模板ID',
  `TEMPLATE_NAME` varchar(100) NOT NULL COMMENT '模板名称快照',
  `MEMBER_NO` bigint NOT NULL COMMENT '会员编号',
  `MEMBER_NAME` varchar(100) DEFAULT NULL COMMENT '会员名称快照',
  `COUPON_CODE` varchar(32) NOT NULL COMMENT '优惠券编码',
  `STATUS` int NOT NULL DEFAULT 0 COMMENT '状态：0未使用 1已锁定 2已用尽 3已过期 4已禁用',
  `USED_COUNT` int NOT NULL DEFAULT 0 COMMENT '已使用次数',
  `REMAINING_USE_COUNT` int NOT NULL DEFAULT 1 COMMENT '剩余可用次数',
  `LOCK_ORDER_NO` varchar(60) DEFAULT NULL COMMENT '锁定订单号',
  `LOCK_TIME` datetime DEFAULT NULL COMMENT '锁定时间',
  `LAST_USE_TIME` datetime DEFAULT NULL COMMENT '最近使用时间',
  `EFFECTIVE_TIME` datetime DEFAULT NULL COMMENT '生效时间',
  `EXPIRE_TIME` datetime DEFAULT NULL COMMENT '过期时间',
  `DELETE_FLAG` varchar(20) NOT NULL DEFAULT 'NOT_DELETE' COMMENT '删除标志',
  `CREATE_TIME` datetime DEFAULT NULL COMMENT '创建时间',
  `CREATE_USER` varchar(20) DEFAULT NULL COMMENT '创建人',
  `UPDATE_TIME` datetime DEFAULT NULL COMMENT '更新时间',
  `UPDATE_USER` varchar(20) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_MEMBER_COUPON_CODE` (`COUPON_CODE`),
  KEY `IDX_MEMBER_COUPON_MEMBER_STATUS` (`MEMBER_NO`,`STATUS`),
  KEY `IDX_MEMBER_COUPON_TEMPLATE` (`TEMPLATE_ID`),
  KEY `IDX_MEMBER_COUPON_LOCK_ORDER_NO` (`LOCK_ORDER_NO`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='会员优惠券表';

CREATE TABLE IF NOT EXISTS `COUPON_ORDER_RELATION` (
  `ID` varchar(20) NOT NULL COMMENT '主键',
  `ORDER_NO` varchar(60) NOT NULL COMMENT '订单号',
  `MEMBER_NO` bigint NOT NULL COMMENT '会员编号',
  `PRODUCT_TYPE` int NOT NULL COMMENT '产品类型',
  `TEMPLATE_ID` varchar(20) NOT NULL COMMENT '模板ID',
  `TEMPLATE_NAME` varchar(100) DEFAULT NULL COMMENT '模板名称快照',
  `MEMBER_COUPON_ID` varchar(20) NOT NULL COMMENT '会员券ID',
  `COUPON_CODE` varchar(32) NOT NULL COMMENT '优惠券编码',
  `COUPON_PRICE` decimal(10,2) NOT NULL DEFAULT 0.00 COMMENT '本次优惠金额',
  `USE_COUNT` int NOT NULL DEFAULT 1 COMMENT '本次使用次数',
  `STATUS` int NOT NULL COMMENT '状态：1已锁定 2已使用 3已释放 4已退回',
  `LOCK_TIME` datetime DEFAULT NULL COMMENT '锁定时间',
  `USE_TIME` datetime DEFAULT NULL COMMENT '使用时间',
  `RELEASE_TIME` datetime DEFAULT NULL COMMENT '释放/退回时间',
  `SNAPSHOT_JSON` varchar(2000) DEFAULT NULL COMMENT '优惠券快照',
  `DELETE_FLAG` varchar(20) NOT NULL DEFAULT 'NOT_DELETE' COMMENT '删除标志',
  `CREATE_TIME` datetime DEFAULT NULL COMMENT '创建时间',
  `CREATE_USER` varchar(20) DEFAULT NULL COMMENT '创建人',
  `UPDATE_TIME` datetime DEFAULT NULL COMMENT '更新时间',
  `UPDATE_USER` varchar(20) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`ID`),
  UNIQUE KEY `UK_COUPON_ORDER_RELATION_ORDER_NO` (`ORDER_NO`),
  KEY `IDX_COUPON_ORDER_RELATION_MEMBER_COUPON_ID` (`MEMBER_COUPON_ID`),
  KEY `IDX_COUPON_ORDER_RELATION_STATUS` (`STATUS`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='订单优惠券关联表';

