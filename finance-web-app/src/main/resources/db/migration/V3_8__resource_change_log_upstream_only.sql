-- 资源变更日志：仅保留与业务表一致的「上游实例主键」UPSTREAM_SERVER_ID，去掉 B_SYSTEM / A_SYSTEM 双列
ALTER TABLE `RESOURCE_CHANGE_LOG`
    ADD COLUMN `UPSTREAM_SERVER_ID` VARCHAR(64) NULL COMMENT '上游/资源池实例主键（与 business_server、business_independent.UPSTREAM_SERVER_ID 一致，拉取方按此对齐）' AFTER `MEMBER_NO`;

UPDATE `RESOURCE_CHANGE_LOG`
SET `UPSTREAM_SERVER_ID` = NULLIF(TRIM(`A_SYSTEM_SERVER_ID`), '')
WHERE `A_SYSTEM_SERVER_ID` IS NOT NULL AND TRIM(`A_SYSTEM_SERVER_ID`) != '';

ALTER TABLE `RESOURCE_CHANGE_LOG` DROP INDEX `IDX_B_SYSTEM_SERVER_ID`;
ALTER TABLE `RESOURCE_CHANGE_LOG` DROP INDEX `IDX_A_SYSTEM_SERVER_ID`;
ALTER TABLE `RESOURCE_CHANGE_LOG` DROP COLUMN `B_SYSTEM_SERVER_ID`;
ALTER TABLE `RESOURCE_CHANGE_LOG` DROP COLUMN `A_SYSTEM_SERVER_ID`;

ALTER TABLE `RESOURCE_CHANGE_LOG` ADD INDEX `IDX_UPSTREAM_SERVER_ID` (`UPSTREAM_SERVER_ID`) USING BTREE COMMENT '上游实例主键索引';
