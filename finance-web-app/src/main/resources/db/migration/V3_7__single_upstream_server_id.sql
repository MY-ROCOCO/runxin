-- 云/独立业务表仅保留「上游（A）实例主键」一列：UPSTREAM_SERVER_ID，删除 B_SYSTEM_SERVER_ID（历史数据合并进 UPSTREAM）
UPDATE `business_server`
SET `UPSTREAM_SERVER_ID` = `B_SYSTEM_SERVER_ID`
WHERE (`UPSTREAM_SERVER_ID` IS NULL OR TRIM(`UPSTREAM_SERVER_ID`) = '')
  AND `B_SYSTEM_SERVER_ID` IS NOT NULL
  AND TRIM(`B_SYSTEM_SERVER_ID`) != '';

ALTER TABLE `business_server` DROP INDEX `IDX_B_SYSTEM_SERVER_ID`;
ALTER TABLE `business_server` DROP COLUMN `B_SYSTEM_SERVER_ID`;

UPDATE `business_independent`
SET `UPSTREAM_SERVER_ID` = `B_SYSTEM_SERVER_ID`
WHERE (`UPSTREAM_SERVER_ID` IS NULL OR TRIM(`UPSTREAM_SERVER_ID`) = '')
  AND `B_SYSTEM_SERVER_ID` IS NOT NULL
  AND TRIM(`B_SYSTEM_SERVER_ID`) != '';

ALTER TABLE `business_independent` DROP INDEX `IDX_B_SYSTEM_SERVER_ID`;
ALTER TABLE `business_independent` DROP COLUMN `B_SYSTEM_SERVER_ID`;
