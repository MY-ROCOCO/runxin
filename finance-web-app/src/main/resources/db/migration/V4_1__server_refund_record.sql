CREATE TABLE IF NOT EXISTS `SERVER_REFUND_RECORD` (
  `ID` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '主键ID',
  `MEMBER_NO` bigint NOT NULL COMMENT '会员编号',
  `SERVER_ID` varchar(60) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '服务器ID',
  `PRODUCT_TYPE` int NOT NULL COMMENT '服务器类型：1云服务器 2独立服务器',
  `SERVER_NAME` varchar(120) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '服务器主机名称',
  `PUBLIC_IP` varchar(60) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '服务器公网IP',
  `REFUND_AMOUNT` decimal(12,2) NOT NULL DEFAULT '0.00' COMMENT '退款金额',
  `STATUS` int NOT NULL DEFAULT 0 COMMENT '状态：0待处理 1已退款 -1已拒绝',
  `CREATE_TIME` datetime DEFAULT NULL COMMENT '创建时间',
  `UPDATE_TIME` datetime DEFAULT NULL COMMENT '更新时间',
  PRIMARY KEY (`ID`) USING BTREE,
  KEY `IDX_MEMBER_NO_STATUS` (`MEMBER_NO`, `STATUS`) USING BTREE,
  KEY `IDX_SERVER_ID_STATUS` (`SERVER_ID`, `STATUS`) USING BTREE,
  KEY `IDX_PRODUCT_TYPE` (`PRODUCT_TYPE`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='服务器退款申请记录表';
